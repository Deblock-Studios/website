/* ═══════════════════════════════════════════════════════════
   i18n controller
   ═══════════════════════════════════════════════════════════ */
const i18n = {
  currentLang: 'fr',

  init() {
    const saved = localStorage.getItem('ds-lang') || 'fr';
    this.setLang(saved, true);
  },

  setLang(lang, silent = false) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('ds-lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = TRANSLATIONS[lang][key];
      if (text !== undefined) el.textContent = text;
    });

    document.querySelectorAll('meta[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = TRANSLATIONS[lang][key];
      if (text !== undefined) el.setAttribute('content', text);
    });

    document.documentElement.lang = lang;

    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    const title = document.querySelector('title');
    if (title) {
      const key = title.getAttribute('data-i18n-title');
      if (key && TRANSLATIONS[lang][key]) title.textContent = TRANSLATIONS[lang][key];
    }

    if (!silent && typeof window.onLangChange === 'function') window.onLangChange();
  },
};
